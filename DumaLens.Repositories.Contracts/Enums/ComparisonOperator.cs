namespace DumaLens.Repositories.Contracts.Enums;

/// <summary>
/// Оператор сравнения процента в фракционном условии поиска
/// </summary>
public enum ComparisonOperator
{
    /// <summary>
    /// Больше или равно (≥)
    /// </summary>
    Gte = 0,

    /// <summary>
    /// Меньше или равно (≤)
    /// </summary>
    Lte = 1,
}